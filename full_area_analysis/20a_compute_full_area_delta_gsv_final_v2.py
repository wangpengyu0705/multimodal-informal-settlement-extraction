def verify_frozen_protocol() -> dict:
    protocol = load_json(FREEZE_MANIFEST)

    if protocol.get("status") != "FROZEN":
        raise ValueError(
            "Final protocol is not FROZEN."
        )

    if int(protocol.get("primary_seed", -1)) != SEED:
        raise ValueError(
            "Final protocol primary seed is not 42."
        )

    final_test = load_json(FINAL_TEST_AUDIT)
    if final_test.get("status") != "PASSED":
        raise ValueError(
            "Final-test audit is not PASSED."
        )

    step16 = load_json(STEP16_AUDIT)
    if step16.get("status") != "PASSED":
        raise ValueError(
            "Step-16 audit is not PASSED."
        )

    if step16.get("training_performed") is not False:
        raise ValueError(
            "Step-16 audit unexpectedly reports training."
        )

    frozen = protocol["frozen_artifact_hashes"]

    path_map = {
        "s2_encoder": S2_ENCODER,
        "gsv_mean_encoder": GSV_MEAN_ENCODER,
        "fusion_mean_model": FUSION_MODEL,
        "fusion_train_only_scaler": FUSION_SCALER,
    }

    for name, path in path_map.items():
        if name not in frozen:
            raise KeyError(
                f"Frozen manifest missing artifact key: {name}"
            )

        rec = frozen[name]

        if Path(rec["path"]) != path:
            raise ValueError(
                f"Frozen artifact path mismatch: {name}"
            )

        actual = sha256_file(path)

        if actual != rec["sha256"]:
            raise ValueError(
                f"Frozen artifact SHA256 mismatch: {name}"
            )

    return protocol


