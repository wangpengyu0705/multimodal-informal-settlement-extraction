def load_scaler():
    scaler = np.load(
        FUSION_SCALER,
        allow_pickle=False,
    )

    required = {
        "s2_mean",
        "s2_std",
        "gsv_mean",
        "gsv_std",
    }

    if set(scaler.files) != required:
        raise ValueError(
            f"Unexpected scaler keys: {set(scaler.files)}"
        )

    arrays = {
        k: scaler[k].astype(np.float32)
        for k in required
    }

    scaler.close()

    for name, arr in arrays.items():
        if arr.shape != (FEATURE_DIM,):
            raise ValueError(
                f"{name}: shape {arr.shape} != {(FEATURE_DIM,)}"
            )
        if not np.isfinite(arr).all():
            raise ValueError(
                f"{name}: non-finite values"
            )

    if np.any(arrays["s2_std"] <= 0):
        raise ValueError(
            "S2 standardization contains non-positive std."
        )

    if np.any(arrays["gsv_std"] <= 0):
        raise ValueError(
            "GSV standardization contains non-positive std."
        )

    return arrays


def compute_split_delta(
    split: str,
    s2_features: np.ndarray,
    gsv_features: np.ndarray,
    labels: np.ndarray,
    index_df: pd.DataFrame,
    model,
    scaler: dict,
):
    expected = (
        EXPECTED_TRAIN
        if split == "train"
        else EXPECTED_VAL
    )

    if len(index_df) != expected:
        raise ValueError(
            f"{split}: index count {len(index_df)} != {expected}"
        )

    if s2_features.shape != (expected, FEATURE_DIM):
        raise ValueError(
            f"{split}: bad S2 feature shape {s2_features.shape}"
        )

    if gsv_features.shape != (expected, FEATURE_DIM):
        raise ValueError(
            f"{split}: bad GSV feature shape {gsv_features.shape}"
        )

    if labels.shape != (expected,):
        raise ValueError(
            f"{split}: bad label shape {labels.shape}"
        )

    index_labels = (
        index_df["label"]
        .astype(np.int8)
        .to_numpy()
    )

    if not np.array_equal(
        labels.astype(np.int8),
        index_labels,
    ):
        raise ValueError(
            f"{split}: feature labels and covered-cell index labels differ."
        )

    s2_z = (
        (s2_features - scaler["s2_mean"])
        / scaler["s2_std"]
    ).astype(np.float32)

    gsv_z = (
        (gsv_features - scaler["gsv_mean"])
        / scaler["gsv_std"]
    ).astype(np.float32)

    neutral_gsv_z = np.zeros(
        (expected, FEATURE_DIM),
        dtype=np.float32,
    )

    if (
        not np.isfinite(s2_z).all()
        or not np.isfinite(gsv_z).all()
    ):
        raise ValueError(
            f"{split}: standardized features contain non-finite values."
        )

    full = model.predict(
        {
            "s2_feature_256": s2_z,
            "gsv_feature_256": gsv_z,
        },
        batch_size=BATCH_SIZE,
        verbose=0,
    ).astype(np.float32)

    neutral = model.predict(
        {
            "s2_feature_256": s2_z,
            "gsv_feature_256": neutral_gsv_z,
        },
        batch_size=BATCH_SIZE,
        verbose=0,
    ).astype(np.float32)

    if full.shape != (expected, 1):
        raise ValueError(
            f"{split}: full probability shape {full.shape}"
        )

    if neutral.shape != (expected, 1):
        raise ValueError(
            f"{split}: neutral probability shape {neutral.shape}"
        )

    full = full[:, 0]
    neutral = neutral[:, 0]

    if (
        not np.isfinite(full).all()
        or not np.isfinite(neutral).all()
    ):
        raise ValueError(
            f"{split}: non-finite Fusion probabilities."
        )

    full_logit = logit(full)
    neutral_logit = logit(neutral)
    delta = full_logit - neutral_logit

    if not np.isfinite(delta).all():
        raise ValueError(
            f"{split}: non-finite ΔGSV."
        )

    out = index_df.copy()

    out["fusion_probability"] = full.astype(np.float64)
    out["gsv_neutralized_probability"] = neutral.astype(np.float64)
    out["full_fusion_logit"] = full_logit
    out["gsv_neutralized_logit"] = neutral_logit
    out["delta_gsv_logit"] = delta
    out["abs_delta_gsv_logit"] = np.abs(delta)
    out["delta_source"] = (
        "frozen_model_forward_pass_on_model_development_data"
    )
    out["evidence_role"] = (
        "model-development descriptive interpretation"
    )

    return out


