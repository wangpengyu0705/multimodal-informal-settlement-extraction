def load_train_val_index() -> pd.DataFrame:
    if not TRAIN_VAL_CELL_INDEX.is_file():
        raise FileNotFoundError(
            TRAIN_VAL_CELL_INDEX
        )

    df = pd.read_csv(
        TRAIN_VAL_CELL_INDEX,
    )

    required = {
        "split",
        "cell_order_within_split",
        "label",
        "patch_order",
        "cell_row",
        "cell_col",
        "global_cell_row",
        "global_cell_col",
        "slot_count",
    }

    missing = sorted(
        required - set(df.columns)
    )

    if missing:
        raise ValueError(
            "TRAIN/VAL cell index missing columns: "
            + ", ".join(missing)
        )

    df["split"] = (
        df["split"]
        .astype(str)
        .str.strip()
        .str.lower()
    )

    df = df[
        df["split"].isin(["train", "val"])
    ].copy()

    counts = (
        df["split"]
        .value_counts()
        .to_dict()
    )

    if counts.get("train", 0) != EXPECTED_TRAIN:
        raise ValueError(
            f"Train covered count {counts.get('train', 0)} "
            f"!= {EXPECTED_TRAIN}"
        )

    if counts.get("val", 0) != EXPECTED_VAL:
        raise ValueError(
            f"Val covered count {counts.get('val', 0)} "
            f"!= {EXPECTED_VAL}"
        )

    if (df["slot_count"] < 1).any():
        raise ValueError(
            "TRAIN/VAL covered index contains slot_count < 1."
        )

    if (df["slot_count"] > 7).any():
        raise ValueError(
            "TRAIN/VAL covered index contains slot_count > 7."
        )

    for split, n in [
        ("train", EXPECTED_TRAIN),
        ("val", EXPECTED_VAL),
    ]:
        sdf = (
            df[df["split"] == split]
            .sort_values("cell_order_within_split")
        )

        observed = (
            sdf["cell_order_within_split"]
            .astype(int)
            .tolist()
        )

        expected = list(range(n))

        if observed != expected:
            raise ValueError(
                f"{split}: cell_order_within_split is not exact 0..{n-1}"
            )

    if df[
        ["global_cell_row", "global_cell_col"]
    ].duplicated().any():
        raise ValueError(
            "Duplicate global TRAIN/VAL covered cells detected."
        )

    return df


def attach_geometry(
    rows: pd.DataFrame,
) -> pd.DataFrame:
    if not CELL_MAPPING.is_file():
        raise FileNotFoundError(
            CELL_MAPPING
        )

    mapping = pd.read_csv(
        CELL_MAPPING,
    )

    required = {
        "split",
        "patch_order",
        "cell_row",
        "cell_col",
        "global_cell_row",
        "global_cell_col",
        "label",
        "valid_cell",
        "is_padding_or_nodata",
        "xmin",
        "ymin",
        "xmax",
        "ymax",
    }

    missing = sorted(
        required - set(mapping.columns)
    )

    if missing:
        raise ValueError(
            "Spatial mapping missing columns: "
            + ", ".join(missing)
        )

    mapping["split"] = (
        mapping["split"]
        .astype(str)
        .str.strip()
        .str.lower()
    )

    valid_map = mapping.loc[
        mapping["valid_cell"].astype(bool)
        & (~mapping["is_padding_or_nodata"].astype(bool))
    ].copy()

    keys = [
        "split",
        "patch_order",
        "cell_row",
        "cell_col",
        "global_cell_row",
        "global_cell_col",
        "label",
    ]

    if valid_map[keys].duplicated().any():
        raise ValueError(
            "Duplicate valid mapping identities detected."
        )

    out = rows.merge(
        valid_map[
            keys
            + [
                "xmin",
                "ymin",
                "xmax",
                "ymax",
            ]
        ],
        on=keys,
        how="left",
        validate="one_to_one",
    )

    if out[
        ["xmin", "ymin", "xmax", "ymax"]
    ].isna().any().any():
        raise ValueError(
            "At least one covered cell failed spatial linkage."
        )

    widths = (
        out["xmax"] - out["xmin"]
    ).to_numpy(float)

    heights = (
        out["ymax"] - out["ymin"]
    ).to_numpy(float)

    if not np.allclose(widths, 80.0):
        raise ValueError(
            "Spatial cell widths are not all 80 m."
        )

    if not np.allclose(heights, 80.0):
        raise ValueError(
            "Spatial cell heights are not all 80 m."
        )

    out["centroid_x"] = (
        out["xmin"] + out["xmax"]
    ) / 2.0

    out["centroid_y"] = (
        out["ymin"] + out["ymax"]
    ) / 2.0

    return out


